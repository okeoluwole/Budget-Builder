/**
 * Test Multi-Source Assumptions API
 * Direct test of the multi-guide calculation endpoint to validate assumptions generation
 */

console.log('🧪 TESTING MULTI-SOURCE ASSUMPTIONS API');
console.log('======================================\n');

async function testMultiSourceAssumptions() {
  const baseURL = 'http://localhost:5000';
  
  const testData = {
    primaryGuide: 'CBRE',
    comparisonGuides: ['TT'],
    project: {
      id: 1,
      country: 'United Kingdom',
      city: 'London',
      totalArea: 1000,
      areaUnit: 'sqm',
      currency: 'USD'
    },
    budget: {
      primaryDataSource: 'CBRE',
      specification: 'Medium (Silver)',
      layout: 'Event',
      selectedScopes: ['Fitout', 'Furniture', 'Technology'],
      includeAVCosts: true,
      includeProfessionalFees: true
    }
  };
  
  console.log('📋 Test Configuration:');
  console.log('Primary Guide:', testData.primaryGuide);
  console.log('Comparison Guide:', testData.comparisonGuides[0]);
  console.log('Location:', `${testData.project.city}, ${testData.project.country}`);
  console.log('Specification:', testData.budget.specification);
  console.log('Layout:', testData.budget.layout);
  
  try {
    console.log('\n🔄 Making API request...');
    const response = await fetch(`${baseURL}/api/calculate-multi-guide`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(testData)
    });
    
    if (!response.ok) {
      throw new Error(`HTTP ${response.status}: ${response.statusText}`);
    }
    
    const result = await response.json();
    
    console.log('\n✅ API Response received');
    console.log('Primary Guide Result:', {
      guideId: result.primary?.guideId,
      totalCost: result.primary?.result?.totalCost,
      currency: result.primary?.result?.localCurrencyCode
    });
    
    console.log('\nComparison Results:');
    result.comparisons?.forEach((comp, index) => {
      console.log(`${index + 1}. ${comp.guideName}:`);
      console.log(`   - Total Cost: ${comp.result?.totalCost}`);
      console.log(`   - Currency: ${comp.result?.localCurrencyCode}`);
      console.log(`   - Data Availability: ${comp.dataAvailability}`);
      console.log(`   - Assumptions Count: ${comp.assumptions?.length || 0}`);
      
      if (comp.assumptions && comp.assumptions.length > 0) {
        console.log('   - Assumptions:');
        comp.assumptions.forEach((assumption, aIndex) => {
          console.log(`     ${aIndex + 1}. ${assumption}`);
        });
      } else {
        console.log('   - ❌ No assumptions generated');
      }
    });
    
    console.log('\nMapping Notes:');
    result.mappingNotes?.forEach((note, index) => {
      console.log(`${index + 1}. ${note}`);
    });
    
    // Validation
    const hasAssumptions = result.comparisons?.some(comp => comp.assumptions && comp.assumptions.length > 0);
    const hasMappingNotes = result.mappingNotes && result.mappingNotes.length > 0;
    
    console.log('\n📊 VALIDATION RESULTS:');
    console.log('Has Assumptions:', hasAssumptions);
    console.log('Has Mapping Notes:', hasMappingNotes);
    console.log('Should Display Component:', hasAssumptions || hasMappingNotes);
    
    if (!hasAssumptions && !hasMappingNotes) {
      console.log('\n❌ ISSUE IDENTIFIED:');
      console.log('No assumptions or mapping notes generated by server');
      console.log('This explains why the frontend component is not displaying');
    } else {
      console.log('\n✅ DATA FLOW CONFIRMED:');
      console.log('Server is generating proper assumptions data');
      console.log('Issue might be in frontend data handling');
    }
    
    return {
      success: true,
      hasAssumptions,
      hasMappingNotes,
      assumptionsCount: result.comparisons?.reduce((total, comp) => total + (comp.assumptions?.length || 0), 0) || 0,
      mappingNotesCount: result.mappingNotes?.length || 0
    };
    
  } catch (error) {
    console.error('\n❌ API Test Failed:', error.message);
    return {
      success: false,
      error: error.message
    };
  }
}

// Run the test
testMultiSourceAssumptions().then(result => {
  console.log('\n🎯 TEST SUMMARY:', result);
  if (result.success) {
    if (result.hasAssumptions || result.hasMappingNotes) {
      console.log('✅ Server-side assumptions generation working correctly');
      console.log('🔍 Check frontend data handling in LevelingAssumptions component');
    } else {
      console.log('❌ Server not generating assumptions - check leveling system');
    }
  } else {
    console.log('❌ API test failed - check server configuration');
  }
});